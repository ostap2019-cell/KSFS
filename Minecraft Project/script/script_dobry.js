// Проходимся по всем мобам и навешиваем обработчики
for (const mobId in dob_mobs) {
    const mob = dob_mobs[mobId];

    // Ищем элементы по ID: img_... и text_...
    const img = document.getElementById("img_" + mob.p);
    const p = document.getElementById("text_" + mob.p);

    // Проверяем, что оба элемента существуют
    if (img && p) {
        // При наведении — вставляем текст и показываем параграф
        img.addEventListener('mouseenter', () => {
            p.textContent = mob.text;
            p.style.display = 'block';
        });

        // При уходе курсора — скрываем параграф
        img.addEventListener('mouseleave', () => {
            p.style.display = 'none';
        });
    } else {
        console.warn(`Не найдены элементы для моба ${mobId} (префикс: ${mob.p})`);
    }
}